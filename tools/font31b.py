def glyph_img(ch, bold):
    top, rows = G[ch]
    w = max(len(r) for r in rows) + (1 if bold else 0)
    im = Image.new("L", (w, ROWS), 0)
    px = im.load()
    for j, r in enumerate(rows):
        for i, c in enumerate(r):
            if c == "#":
                px[i, top + j] = 255
                if bold:
                    px[i + 1, top + j] = 255
    return im


def scale2x(im):
    """Scale2x (EPX): увеличение пиксель-арта ×2 со сглаживанием диагоналей — для крупного заголовочного шрифта."""
    w, h = im.size
    src = im.load()
    out = Image.new("L", (w * 2, h * 2), 0)
    o = out.load()

    def P(x, y):
        return src[x, y] if 0 <= x < w and 0 <= y < h else 0
    for y in range(h):
        for x in range(w):
            p = P(x, y)
            a, b, c, d = P(x, y - 1), P(x + 1, y), P(x - 1, y), P(x, y + 1)
            e0 = a if (c == a and c != d and a != b) else p
            e1 = b if (a == b and a != c and b != d) else p
            e2 = c if (d == c and d != b and c != a) else p
            e3 = d if (b == d and b != a and d != c) else p
            o[2 * x, 2 * y], o[2 * x + 1, 2 * y], o[2 * x, 2 * y + 1], o[2 * x + 1, 2 * y + 1] = e0, e1, e2, e3
    return out


def build(name, bold, big=False):
    chars = [" ", " "] + sorted(G.keys())
    aw = 512
    x = y = 0
    places = []
    for ch in chars:
        if ch in (" ", " "):
            places.append((ch, None, (SPACE + (1 if bold else 0)) * (2 if big else 1), 0, 0))
            continue
        im = glyph_img(ch, bold)
        if big:
            im = scale2x(im)
        if x + im.width + 1 > aw:
            x = 0
            y += im.height + 1
        places.append((ch, im, im.width + (2 if big else 1), x, y))
        x += im.width + 1
    rows = ROWS * (2 if big else 1)
    ah = y + rows + 1
    atlas = Image.new("RGBA", (aw, ah), (0, 0, 0, 0))
    for ch, im, adv, gx, gy in places:
        if im:
            atlas.paste(Image.new("RGBA", im.size, (255, 255, 255, 255)), (gx, gy), im)
    atlas.save(os.path.join(GAME, "fonts", name + ".png"))
    lines = [
        'info face="%s" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0' % (name, LINE * (2 if big else 1)),
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4" % (LINE * (2 if big else 1), BASE * (2 if big else 1), aw, ah),
        'page id=0 file="%s.png"' % name,
        "chars count=%d" % len(places),
    ]
    for ch, im, adv, gx, gy in places:
        lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
                     % (ord(ch), gx, gy, im.width if im else 0, im.height if im else 0, adv))
    open(os.path.join(GAME, "fonts", name + ".fnt"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    return places


